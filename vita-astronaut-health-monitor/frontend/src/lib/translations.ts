export type TranslationKey = keyof typeof translations.uk;

export function translate(
  locale: Locale,
  key: TranslationKey | string,
  vars?: Record<string, string | number>,
): string {
  const table = translations[locale] as Record<string, string>;
  const fallback = translations.uk as Record<string, string>;
  let text = table[key] ?? fallback[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function hasTranslation(key: string): key is TranslationKey {
  return key in translations.uk;
}
